"""Research planning, tasks, and project configuration schemas."""

import uuid
from typing import List, Optional
from pydantic import BaseModel, Field


class ResearchScope(BaseModel):
    """Scope constraints for an autonomous research review."""

    date_range_start: Optional[int] = Field(default=None, description="Earliest publication year")
    date_range_end: Optional[int] = Field(default=None, description="Latest publication year")
    max_papers: int = Field(default=20, ge=1, le=100, description="Target number of papers to review")
    preferred_sources: List[str] = Field(
        default_factory=lambda: ["arxiv", "semantic_scholar"],
        description="Target academic repositories",
    )


class ResearchTask(BaseModel):
    """A single bounded subquestion query dispatched to search workers."""

    task_id: str = Field(
        default_factory=lambda: f"task-{uuid.uuid4().hex[:8]}",
        description="Unique identifier for the research task",
    )
    subquestion: str = Field(description="Specific research subquestion to investigate")
    query: str = Field(description="Optimized search query string for academic APIs")
    keywords: List[str] = Field(
        default_factory=list, description="Associated keywords and alternative terms"
    )
    priority: int = Field(default=1, description="Priority rank (1 being highest)")


class ResearchPlan(BaseModel):
    """Complete structured plan generated by the Planner Agent."""

    research_question: str = Field(description="The primary user research question")
    objective: str = Field(description="Synthesized research objective")
    tasks: List[ResearchTask] = Field(
        min_length=1, description="List of orthogonal subquestion research tasks"
    )
    inclusion_criteria: List[str] = Field(
        default_factory=list, description="Rules determining whether a paper is included"
    )
    exclusion_criteria: List[str] = Field(
        default_factory=list, description="Rules determining whether a paper is excluded"
    )

